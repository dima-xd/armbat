#!/usr/bin/env python3
"""Embed a binary file as a C++ byte array (used for guest .so images)."""

import argparse
import pathlib


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--namespace", required=True, help="e.g. armbat::generated")
    parser.add_argument("--name", required=True, help="C++ identifier prefix")
    args = parser.parse_args()

    data = pathlib.Path(args.input).read_bytes()
    if not data:
        raise SystemExit("empty input: " + args.input)

    guards = []
    for line in [
        "// Generated by tools/gen_embedded_binary.py. Do not edit.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace " + args.namespace + " {",
        "",
        "inline constexpr unsigned char {}Image[{}] = {{".format(args.name, len(data)),
    ]:
        guards.append(line)

    for offset in range(0, len(data), 16):
        chunk = data[offset : offset + 16]
        guards.append("    " + ", ".join("0x{:02x}".format(b) for b in chunk) + ",")

    guards.append("};")
    guards.append("")
    guards.append("inline constexpr std::uint32_t {}Size = {}u;".format(args.name, len(data)))
    guards.append("")
    guards.append("}  // namespace " + args.namespace)
    guards.append("")

    out = pathlib.Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(guards), encoding="utf-8")


if __name__ == "__main__":
    main()
