#!/usr/bin/env python3
"""Compile the ARMv7 guest test routines into a flat blob plus symbol offsets.

The generated header carries the raw .text image and the address of every
exported routine, so the runtime only needs to memcpy the blob into the arena at
kGuestLoadAddress. The ELF32 loader is exercised separately, by real shared
objects built from tests/guest/native_lib.c.
"""

import argparse
import pathlib
import struct
import subprocess
import sys
import tempfile

GUEST_BASE = 0x1000
GUEST_TRIPLE = "armv7a-linux-androideabi31"


def run(cmd):
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode != 0:
        sys.stderr.write("command failed: {}\n{}\n{}\n".format(" ".join(cmd), result.stdout, result.stderr))
        raise SystemExit(1)
    return result.stdout


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--clang", required=True)
    parser.add_argument("--objcopy", required=True)
    parser.add_argument("--nm", required=True)
    parser.add_argument("--source", required=True)
    parser.add_argument("--out", required=True)
    args = parser.parse_args()

    source = pathlib.Path(args.source)
    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)

    common = [
        args.clang,
        "--target=" + GUEST_TRIPLE,
        "-march=armv7-a",
        "-mfpu=neon",
        "-mfloat-abi=softfp",
        "-marm",
        "-O2",
        "-std=c11",
        "-ffreestanding",
        "-fno-builtin",
        "-fno-stack-protector",
        "-fno-vectorize",
        "-fno-slp-vectorize",
        "-fomit-frame-pointer",
        "-fno-asynchronous-unwind-tables",
        "-fno-unwind-tables",
    ]

    with tempfile.TemporaryDirectory() as tmp:
        tmp = pathlib.Path(tmp)
        obj = tmp / "guest_functions.o"
        elf = tmp / "guest_functions.elf"
        blob = tmp / "guest_functions.bin"

        run(common + ["-c", str(source), "-o", str(obj)])
        run(
            common
            + [
                "-nostdlib",
                "-static",
                "-Wl,--build-id=none",
                "-Wl,--no-undefined",
                "-Wl,-e,add",
                "-Wl,--section-start=.text={:#x}".format(GUEST_BASE),
                str(obj),
                "-o",
                str(elf),
            ]
        )

        symbols_output = run([args.nm, "--defined-only", "--format=posix", str(elf)])
        symbols = {}
        for line in symbols_output.splitlines():
            parts = line.split()
            if len(parts) >= 3 and parts[1] in ("T", "t"):
                symbols[parts[0]] = int(parts[2], 16)

        run([args.objcopy, "-O", "binary", str(elf), str(blob)])
        data = blob.read_bytes()

        if not symbols:
            sys.stderr.write("no text symbols found in {}\n".format(elf))
            raise SystemExit(1)
        if len(data) < 128:
            sys.stderr.write("suspiciously small guest blob: {} bytes\n".format(len(data)))
            raise SystemExit(1)

        lines = [
            "// Generated by tools/gen_guest_blob.py. Do not edit.",
            "#pragma once",
            "",
            "#include <cstdint>",
            "",
            "namespace armbat::generated {",
            "",
            "inline constexpr std::uint32_t kGuestLoadAddress = {:#x}u;".format(GUEST_BASE),
            "inline constexpr std::uint32_t kGuestBlobSize = {}u;".format(len(data)),
            "",
            "inline constexpr unsigned char kGuestBlob[kGuestBlobSize] = {",
        ]
        for offset in range(0, len(data), 16):
            chunk = data[offset : offset + 16]
            lines.append("    " + ", ".join("0x{:02x}".format(b) for b in chunk) + ",")
        lines.append("};")
        lines.append("")
        lines.append("namespace sym {")
        for name in sorted(symbols):
            address = symbols[name] - GUEST_BASE
            if address < 0 or address >= len(data):
                sys.stderr.write("symbol {} outside blob: {:#x}\n".format(name, address))
                raise SystemExit(1)
            lines.append("inline constexpr std::uint32_t {} = {:#x}u;".format(name, address))
        lines.append("}  // namespace sym")
        lines.append("")
        lines.append("}  // namespace armbat::generated")
        lines.append("")

        out.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
