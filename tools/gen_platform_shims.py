#!/usr/bin/env python3
"""Generates the guest platform shim libraries.

A 32-bit game links against the Android platform libraries (libEGL, libGLESv2,
libandroid, liblog, libOpenSLES, ...). The container does not run the device's
real implementations of those APIs: it implements them on the host side, in the
HLE registry. The guest still has to *load* something called libEGL.so, and the
linker still has to resolve every symbol the game imports.

So each shim library exports exactly the API surface of its Android 7 (API 24)
counterpart and contains one tiny trampoline per symbol:

    name:
        adr r12, 1f      @ address of the symbol name
        svc #0xFFFE      @ "dispatch the HLE function named in r12"
        bx lr
    1:  .asciz "name"

Nothing is hard-coded per game or per SDK: the symbol list comes from the NDK's
own API-24 stub library for that platform library, which is the same list a real
device exposes. A name the container does not implement yet resolves and returns
zero, and logs itself once.

Exported objects (the SL_IID_* interface identifiers) become pointers to a
unique descriptor: a magic word, a pointer to the symbol's own name, and two
spare words. A non-null token whose identity is the only thing that matters on
a device becomes something the container can name, which is how OpenSL ES
interface lookups are answered without a table of load-address-dependent
values.

Usage:
  gen_platform_shims.py --ndk <ndk> --out <dir> [--api 24] [library ...]
"""

from __future__ import annotations

import argparse
import os
import struct
import subprocess
import sys

SHT_DYNSYM = 11
STB_GLOBAL = 1
STB_WEAK = 2
STB_GNU_UNIQUE = 10
STT_OBJECT = 1
STT_FUNC = 2
STT_GNU_IFUNC = 10
STT_TLS = 6

# Libraries every Android 7 armeabi-v7a device exposes that games actually link
# against. The list is deliberately the platform's, not any one game's.
DEFAULT_LIBRARIES = [
    "libEGL",
    "libGLESv1_CM",
    "libGLESv2",
    "libandroid",
    "libjnigraphics",
    "liblog",
    "libOpenSLES",
]


def read_dynsym(path: str) -> list[tuple[str, int]]:
    """Returns (name, {FUNC, OBJECT}) for every exported dynamic symbol."""
    with open(path, "rb") as handle:
        data = handle.read()
    if data[:4] != b"\x7fELF" or data[4] != 1 or data[5] != 1:
        raise SystemExit(f"{path}: not a little-endian ELF32 file")

    (e_shoff,) = struct.unpack_from("<I", data, 0x20)
    (e_shentsize, e_shnum, e_shstrndx) = struct.unpack_from("<HHH", data, 0x2E)

    sections = []
    for index in range(e_shnum):
        base = e_shoff + index * e_shentsize
        sections.append(struct.unpack_from("<IIIIIIIIII", data, base))

    def section_name(offset: int) -> str:
        header = sections[e_shstrndx]
        start = header[4] + offset
        end = data.index(b"\0", start)
        return data[start:end].decode("ascii", "replace")

    symbols: list[tuple[str, int]] = []
    seen: set[str] = set()
    for header in sections:
        if header[1] != SHT_DYNSYM:
            continue
        strtab = sections[header[6]]
        entries = header[5] // 16
        for index in range(entries):
            base = header[4] + index * 16
            st_name, _value, _size, st_info, st_other, st_shndx = struct.unpack_from(
                "<IIIBBH", data, base
            )
            if st_shndx == 0 or st_name == 0:
                continue
            bind = st_info >> 4
            kind = st_info & 0x0F
            if bind not in (STB_GLOBAL, STB_WEAK, STB_GNU_UNIQUE):
                continue
            if (st_other & 0x03) not in (0, 3):
                continue
            if kind in (STT_TLS, STT_GNU_IFUNC):
                continue
            if kind not in (STT_FUNC, STT_OBJECT):
                continue
            start = strtab[4] + st_name
            end = data.index(b"\0", start)
            name = data[start:end].decode("ascii", "replace")
            if not name or name in seen:
                continue
            seen.add(name)
            symbols.append((name, kind))
    return symbols


def emit_assembly(library: str, symbols: list[tuple[str, int]]) -> str:
    lines = [
        f"@ Generated by tools/gen_platform_shims.py for {library}. Do not edit.",
        f"@ Every entry point traps into Armbat's HLE registry by name.",
        "\t.syntax unified",
        "\t.arm",
        "",
    ]
    objects = []
    for name, kind in symbols:
        if kind == STT_FUNC:
            lines += [
                "\t.text",
                f"\t.global {name}",
                f"\t.type {name}, %function",
                f"{name}:",
                "\tadr r12, 1f",
                "\tsvc #0xFFFE",
                "\tbx lr",
                "1:",
                f'\t.asciz "{name}"',
                "\t.align 2",
                "",
            ]
        else:
            # An exported object is a variable whose address the guest takes, so
            # it becomes a word pointing at a descriptor of its own. Distinct
            # addresses keep identity comparisons between the SL_IID_* values
            # working the way they do on a device. The descriptor also names its
            # own symbol: OpenSL ES asks for an interface by identity, and a name
            # is the only identity the container can read out of guest memory
            # without knowing the load address of this library.
            objects.append(name)
            lines += [
                "\t.data",
                f"\t.global {name}",
                f"\t.type {name}, %object",
                f"\t.size {name}, 4",
                f"{name}:",
                f"\t.word {name}_armbat_body",
                "\t.align 2",
                f"{name}_armbat_body:",
                "\t.word 0x41524254",
                f"\t.word {name}_armbat_id",
                "\t.word 0, 0",
                f"{name}_armbat_id:",
                f'\t.asciz "{name}"',
                "\t.align 2",
                "",
            ]
    lines.append('\t.section .note.GNU-stack,"",%progbits')
    lines.append("")
    return "\n".join(lines)


def build(ndk: str, out_dir: str, api: int, libraries: list[str]) -> int:
    toolchain = os.path.join(ndk, "toolchains", "llvm", "prebuilt")
    platforms = os.listdir(toolchain)
    if not platforms:
        raise SystemExit(f"{toolchain}: no prebuilt toolchain")
    host = platforms[0]
    bin_dir = os.path.join(toolchain, host, "bin")
    clang = os.path.join(bin_dir, "clang.exe" if os.name == "nt" else "clang")
    stub_root = os.path.join(
        toolchain, host, "sysroot", "usr", "lib", "arm-linux-androideabi", str(api)
    )
    if not os.path.isdir(stub_root):
        raise SystemExit(f"{stub_root}: no API {api} stub libraries")

    text_dir = os.path.join(out_dir, "asm")
    lib_dir = os.path.join(out_dir, "lib")
    os.makedirs(text_dir, exist_ok=True)
    os.makedirs(lib_dir, exist_ok=True)

    for library in libraries:
        stub = os.path.join(stub_root, library + ".so")
        if not os.path.isfile(stub):
            print(f"skip {library}: no API {api} stub", file=sys.stderr)
            continue
        symbols = read_dynsym(stub)
        funcs = sum(1 for _, kind in symbols if kind == STT_FUNC)
        source = os.path.join(text_dir, library + ".S")
        with open(source, "w", encoding="ascii", newline="\n") as handle:
            handle.write(emit_assembly(library, symbols))
        target = os.path.join(lib_dir, library + ".so")
        command = [
            clang,
            "--target=armv7a-linux-androideabi" + str(api),
            "-march=armv7-a",
            "-mfloat-abi=softfp",
            "-mfpu=vfpv3-d16",
            "-O2",
            "-fPIC",
            "-shared",
            "-nostdlib",
            "-Wl,-soname," + library + ".so",
            "-Wl,--build-id=none",
            "-Wl,-z,noexecstack",
            "-o",
            target,
            source,
        ]
        result = subprocess.run(command, capture_output=True, text=True)
        if result.returncode != 0:
            sys.stderr.write(result.stdout)
            sys.stderr.write(result.stderr)
            return result.returncode
        print(f"{library}: {funcs} functions, {len(symbols) - funcs} objects -> {target}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ndk", required=True, help="Android NDK root")
    parser.add_argument("--out", required=True, help="output directory")
    parser.add_argument("--api", type=int, default=24)
    parser.add_argument("libraries", nargs="*", default=DEFAULT_LIBRARIES)
    arguments = parser.parse_args()
    return build(arguments.ndk, arguments.out, arguments.api, arguments.libraries)


if __name__ == "__main__":
    raise SystemExit(main())
